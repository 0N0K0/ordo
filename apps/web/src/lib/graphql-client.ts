import type { TypedDocumentString } from '../graphql/graphql';

const ENDPOINT = '/api/graphql';

/** Workspace this tab shows: its requests stay in it, even when another tab switches (the cookie is shared). */
let workspaceId: string | null = null;

/**
 * Pins the requests of this tab to a workspace.
 * @param {string | null} id Workspace, or null to follow the cookie.
 * @returns {void}
 */
export function pinWorkspace(id: string | null): void {
  workspaceId = id;
}

interface GraphQLErrorPayload {
  message: string;
  extensions?: { code?: string; fields?: Record<string, string> };
}

/** Error returned by the API, with its code and per-field messages. */
export class GraphQLRequestError extends Error {
  readonly code: string;
  readonly fields: Record<string, string>;

  /**
   * @param {GraphQLErrorPayload} payload First error of the GraphQL response.
   */
  constructor(payload: GraphQLErrorPayload) {
    super(payload.message);
    this.name = 'GraphQLRequestError';
    this.code = payload.extensions?.code ?? 'INTERNAL_SERVER_ERROR';
    this.fields = payload.extensions?.fields ?? {};
  }
}

/**
 * Replaces every File in the variables by null and collects their paths
 * (GraphQL multipart request spec).
 * @param {unknown} value Variables, or a nested value.
 * @param {string} path Path of `value` from the operation root.
 * @param {Map<File, string[]>} files Collected files with their paths.
 * @returns {unknown} Value with files replaced by null.
 */
function extractFiles(value: unknown, path: string, files: Map<File, string[]>): unknown {
  if (value instanceof File) {
    files.set(value, [...(files.get(value) ?? []), path]);
    return null;
  }
  if (Array.isArray(value)) return value.map((item, index) => extractFiles(item, `${path}.${index}`, files));
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, extractFiles(item, `${path}.${key}`, files)]),
    );
  }
  return value;
}

/**
 * Builds the request body: JSON, or multipart when the variables hold files.
 * @param {string} query Operation source.
 * @param {unknown} variables Operation variables.
 * @returns {{ body: BodyInit, headers: Record<string, string> }} Body and headers to send.
 */
function buildBody(query: string, variables: unknown): { body: BodyInit; headers: Record<string, string> } {
  const files = new Map<File, string[]>();
  const cleanVariables = extractFiles(variables, 'variables', files);
  const operations = JSON.stringify({ query, variables: cleanVariables });

  if (files.size === 0) {
    return { body: operations, headers: { 'content-type': 'application/json' } };
  }

  const form = new FormData();
  form.append('operations', operations);
  const entries = [...files.entries()];
  form.append('map', JSON.stringify(Object.fromEntries(entries.map(([, paths], index) => [index, paths]))));
  entries.forEach(([file], index) => form.append(String(index), file, file.name));
  // The browser sets the multipart content-type with its boundary.
  return { body: form, headers: {} };
}

/**
 * Runs a typed GraphQL operation against the API (session cookie included), in the workspace of this tab.
 * Variables containing File objects are sent as a multipart request.
 * @param {TypedDocumentString<TResult, TVariables>} document Operation generated by codegen.
 * @param {TVariables} [variables] Operation variables. Optional when the operation has none.
 * @returns {Promise<TResult>} Operation data.
 */
export function execute<TResult, TVariables>(
  document: TypedDocumentString<TResult, TVariables>,
  ...[variables]: TVariables extends Record<string, never> ? [] : [TVariables]
): Promise<TResult> {
  return request(workspaceId, document.toString(), variables);
}

/**
 * Runs a typed GraphQL operation in another workspace than the one of this tab (its notifications).
 * @param {string} workspace Workspace.
 * @param {TypedDocumentString<TResult, TVariables>} document Operation generated by codegen.
 * @param {TVariables} [variables] Operation variables. Optional when the operation has none.
 * @returns {Promise<TResult>} Operation data.
 */
export function executeIn<TResult, TVariables>(
  workspace: string,
  document: TypedDocumentString<TResult, TVariables>,
  ...[variables]: TVariables extends Record<string, never> ? [] : [TVariables]
): Promise<TResult> {
  return request(workspace, document.toString(), variables);
}

/**
 * Sends an operation to the API.
 * @param {string | null} workspace Workspace it runs in; null follows the cookie.
 * @param {string} query Operation source.
 * @param {unknown} variables Operation variables.
 * @returns {Promise<TResult>} Operation data.
 */
async function request<TResult>(workspace: string | null, query: string, variables: unknown): Promise<TResult> {
  const { body, headers } = buildBody(query, variables);
  let response: Response;
  try {
    response = await fetch(ENDPOINT, {
      method: 'POST',
      credentials: 'same-origin',
      headers: { ...headers, accept: 'application/json', ...(workspace ? { 'x-ordo-workspace': workspace } : {}) },
      body,
    });
  } catch {
    throw new GraphQLRequestError({ message: 'Le serveur est injoignable.', extensions: { code: 'NETWORK_ERROR' } });
  }

  const json = (await response.json().catch(() => null)) as { data?: TResult; errors?: GraphQLErrorPayload[] } | null;
  if (json?.errors?.length) throw new GraphQLRequestError(json.errors[0]);
  if (!response.ok || !json?.data) {
    throw new GraphQLRequestError({ message: 'Une erreur inattendue est survenue.' });
  }
  return json.data;
}
